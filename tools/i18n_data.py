def _late(ru: str) -> bool:
    """Общий шаблон: мало текста вокруг подстановок и начинается с подстановки - после разбора по разделителям."""
    lit = re.sub(r"\{\w+\}", "", ru)
    return ru.startswith("{") and len(lit.strip(" .,:;()-")) < 12


