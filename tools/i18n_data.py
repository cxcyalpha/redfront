    cyr = re.compile("[А-Яа-яЁё]")
    extra = {}
    def walk(x, k=None):
        if isinstance(x, dict):
            for kk, v in x.items():
                walk(v, kk)
        elif isinstance(x, list):
            for v in x:
                walk(v, k)
        elif isinstance(x, str) and k in ("name", "title", "alias") and cyr.search(x) and x not in names:
            e = i18n_en.en(x)
            if not cyr.search(e):
                extra[x] = e
